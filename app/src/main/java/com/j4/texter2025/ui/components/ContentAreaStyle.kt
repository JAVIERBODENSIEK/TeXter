package com.j4.texter2025.ui.components

/**
 * Defines style options for the content area display
 */
enum class ContentAreaStyle(val displayName: String) {
    /**
     * Edge-to-Edge style with no padding
     */
    EDGE_TO_EDGE("Edge-to-Edge (No Padding)"),
    
    /**
     * Dialog style with rounded corners, elevation and padding
     */
    DIALOG("Dialog Style (Rounded, Elevated, Padded)")
}
